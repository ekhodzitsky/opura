#!/usr/bin/env python3
"""Optional original pinned CELT band arithmetic oracle; never a Cargo dependency."""
import argparse
import ctypes as c
import math
from pathlib import Path
import subprocess
import tempfile

REVISION = '22244de5a79bd1d6d623c32e72bf1954b56235be'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('source', type=Path)
parser.add_argument('--tables', action='store_true')
args = parser.parse_args()
source = args.source.resolve()
if subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip() != REVISION:
    raise SystemExit('Expected pinned Opus v1.6.1')
if subprocess.check_output(['git', '-C', str(source), 'status', '--porcelain'], text=True).strip():
    raise SystemExit('Reference checkout must be clean')

def function(text, signature):
    start = text.index(signature)
    brace = text.index('{', start)
    depth = 1
    end = brace + 1
    while depth:
        depth += (text[end] == '{') - (text[end] == '}')
        end += 1
    return text[start:end] + '\n'

bands = (source / 'celt/bands.c').read_text()
vq = (source / 'celt/vq.c').read_text()
start = bands.index('static const int ordery_table[]')
order = bands[start:bands.index(';', start) + 1]
wrapper = '''
#include "arch.h"
#include "mathops.h"
#include "vq.h"
#include "bands.h"
#include "stack_alloc.h"
#include "os_support.h"
#if !OPUS_FAST_INT64
#error "Canonical band oracle requires scalar fast-64-bit math"
#endif
'''
for signature in ['void norm_scaleup(', 'void norm_scaledown(', 'opus_val32 celt_inner_prod_norm(',
                  'opus_val32 celt_inner_prod_norm_shift(', 'void renormalise_vector(']:
    wrapper += function(vq, signature)
wrapper += order + '\n'
for signature in ['opus_int16 bitexact_cos(', 'int bitexact_log2tan(', 'static void stereo_merge(',
                  'static void deinterleave_hadamard(', 'static void interleave_hadamard(', 'void haar1(']:
    wrapper += function(bands, signature)
wrapper += '''
int constant(int i) { return i==0 ? QCONST32(.70710678f,31) : QCONST32(6e-4f,28); }
int ordering(int i) {return ordery_table[i];}
void vector(int op,int *x,int n,int stride,int had,int gain) {
    if(op==0) deinterleave_hadamard(x,n/stride,stride,had);
    if(op==1) interleave_hadamard(x,n/stride,stride,had);
    if(op==2) haar1(x,n/stride,stride);
    if(op==3) renormalise_vector(x,n,gain,0);
}
void merge(int *x,int *y,int mid,int n) {stereo_merge(x,y,mid,n,0);}
'''
with tempfile.TemporaryDirectory(prefix='opura-celt-bands-') as temp:
    path = Path(temp)
    (path / 'probe.c').write_text(wrapper)
    subprocess.run(['cc', '-shared', '-fPIC', '-O2', '-fwrapv', '-DFIXED_POINT', '-DVAR_ARRAYS',
                    '-DOPUS_BUILD', '-DDISABLE_FLOAT_API', '-I'+str(source/'include'), '-I'+str(source/'celt'),
                    str(path/'probe.c'), str(source/'celt/mathops.c'), str(source/'celt/entcode.c'),
                    '-o', str(path/'probe.so')], check=True)
    lib = c.CDLL(str(path/'probe.so'))
    ptr = c.POINTER(c.c_int32)
    for name, types, result in [('constant',[c.c_int],c.c_int), ('ordering',[c.c_int],c.c_int),
                              ('bitexact_cos',[c.c_int16],c.c_int16),
                              ('bitexact_log2tan',[c.c_int,c.c_int],c.c_int),
                              ('vector',[c.c_int,ptr,*[c.c_int]*4],None),
                              ('merge',[ptr,ptr,c.c_int,c.c_int],None)]:
        fn = getattr(lib,name); fn.argtypes=types; fn.restype=result
    if args.tables:
        print('// Original classic CELT constants/order, Opus v1.6.1 '+REVISION)
        print('// Generated by tools/celt_band_fixtures.py --tables; see THIRD_PARTY_NOTICES.md.')
        print('pub(super) const HAAR_Q31: i32 = %d;' % lib.constant(0))
        print('pub(super) const MIN_STEREO_Q28: i32 = %d;' % lib.constant(1))
        print('pub(super) const ORDER: [u8;30] = [%s];' % ','.join(str(lib.ordering(i)) for i in range(30)))
        raise SystemExit
    print('# Original classic CELT bands/vq scalar oracle:', REVISION)
    print('# theta ANGLE COS SIN; log SINE COS RESULT; logblock START COUNT STEP SINE FNV1A64(le-i32)')
    print('# vector OP N STRIDE HAD GAIN INPUT[N] OUTPUT[N]; merge N MID INPUT[2*N] OUTPUT[2*N]')
    for theta in [0,*range(64,16321),16384]:
        gains = [32767,0] if theta==0 else [0,32767] if theta==16384 else [lib.bitexact_cos(theta),lib.bitexact_cos(16384-theta)]
        print('theta',theta,*gains)
    for sine in range(1,257):
        fingerprint=14695981039346656037
        for cosine in range(1,257):
            result=lib.bitexact_log2tan(sine,cosine)
            for byte in (result & 0xffffffff).to_bytes(4,'little'):
                fingerprint=((fingerprint^byte)*1099511628211)&0xffffffffffffffff
        print('logblock',1,256,1,sine,fingerprint)
    for sine in [1,2,63,64,255,256,8191,8192,16383,16384,32766,32767]:
        for cosine in range(1,32768,127):
            print('log',sine,cosine,lib.bitexact_log2tan(sine,cosine))
    random=0x42414e44
    def next_random():
        global random
        random ^= (random<<13)&0xffffffff; random ^= random>>17; random ^= (random<<5)&0xffffffff
        return c.c_int32(random).value
    def vector(op,values,stride=1,had=0,gain=0):
        data=(c.c_int32*len(values))(*values)
        lib.vector(op,data,len(values),stride,had,gain)
        print('vector',op,len(values),stride,had,gain,*values,*data)
    for stride in [1,2,4,8,16]:
        for n in range(stride,177,stride):
            for had in range(1 if stride==1 else 2):
                values=[next_random() for _ in range(n)]
                for op in [0,1]:vector(op,values,stride,had)
    for stride in [1,2,4,8,16,32,64]:
        for n in range(2*stride,177,2*stride):
            for pattern in range(3):
                values=[([0x7fffffff,-0x80000000,1,-1][i%4] if pattern==0 else i-90 if pattern==1 else next_random()) for i in range(n)]
                vector(2,values,stride)
    for n in [1,2,3,4,8,16,22,44,88,176]:
        for gain in [0,1,1<<28,1<<30,32767<<16,0x7fffffff]:
            for pattern in range(7):
                values=[(0 if pattern==0 else (1<<24 if i==0 else 0) if pattern==1 else 1 if pattern==2 else -513 if pattern==3 else (next_random()>>20)<<10 if pattern==4 else (next_random()%65535-32767)*1024//math.isqrt(n+1) if pattern==5 else (32767 if i==0 else 0)*1024) for i in range(n)]
                vector(3,values,gain=gain)
        for mid in [0,1,1<<28,1<<30,0x7fffffff]:
            for pattern in range(8):
                left=[(1<<24 if i==0 else 0) if pattern<4 else (next_random()%65535-32767)*(1<<9)//math.isqrt(n+1) for i in range(n)]
                right=[(0 if pattern==0 else left[i] if pattern==1 else -left[i] if pattern==2 else (1<<24 if i==n-1 else 0) if pattern==3 else (next_random()%65535-32767)*(1<<9)//math.isqrt(n+1)) for i in range(n)]
                x=(c.c_int32*n)(*left); y=(c.c_int32*n)(*right)
                lib.merge(x,y,mid,n)
                print('merge',n,mid,*left,*right,*x,*y)
